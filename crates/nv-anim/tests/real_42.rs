#[test]
fn a_real_4_2_skeleton_reads() {
    let atlas = Atlas::parse("page.png
size:64,64
anticipationv2/anticipationv2_
bounds:0,0,8,8
").unwrap();
    let rig = binary::parse(SKEL, atlas).expect("a real 4.2.43 file");
    assert_eq!(rig.version, "4.2.43");
    assert_eq!((rig.width, rig.height), (300.0, 900.0));
    assert_eq!(rig.bones.len(), 1);
    assert_eq!(rig.bones[0].name, "root");
    assert_eq!(rig.slots.len(), 1);
    assert_eq!(rig.slots[0].name, "anticipation");
    assert_eq!(rig.animations.len(), 1);
    assert_eq!(rig.animations[0].name, "animation");
    // the attachment is a region of the image sequence
    assert!(matches!(rig.find_attachment(0, 0, "anticipationv2/anticipationv2_"), Some((nv_anim::Attachment::Region(_), _))));
}
